def feedback_snapshots(eligible_steps):
    """Select by index only, before consulting measured gains."""
    steps = sorted(set(int(k) for k in eligible_steps))
    if not steps:
        return []
    positions = {0, 1, 2, 4, 9, math.floor(0.5 * (len(steps) - 1)), len(steps) - 1}
    return [steps[p] for p in sorted(positions) if 0 <= p < len(steps)]


def synchronization_snapshots(prediction_steps, eligible_steps):
    steps = sorted(set(int(k) for k in prediction_steps))
    if not steps:
        return []
    length = max(1, len(set(eligible_steps)))
    indices = (0, math.ceil(0.2 * length), math.floor(0.5 * (length - 1)), length - 1)
    return [
        (name, steps[min(max(0, index), len(steps) - 1)])
        for name, index in zip(("initial", "early", "middle", "late"), indices)
    ]


